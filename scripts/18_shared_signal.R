# ==============================================================
# Shared blood DNA methylation signatures of comorbid disorders (PD x IBD)
# Step 18: test of sharing (primary criterion)
#
# The order of the tests is deliberate: positive controls first, then the primary criterion:
#
#   positive controls  PD discovery set vs PD replication set; IBD main set vs IBD paediatric set
#             If no concordance of effect sizes can be detected between two independent cohorts of the same disease,
#             the criterion has no power at the present sample sizes and noise level,
#             and a negative cross-disease result carries no information. The outcome of this step
#             decides how all later conclusions are read, so it must be examined first.
#   primary criterion  PD discovery set vs IBD main set
#   secondary          PD replication set vs IBD main set
#   negative controls  PD vs schizophrenia; IBD vs schizophrenia
#
# The null distribution is generated by randomly permuting case-control labels within a cohort. The effect sizes recomputed
# after permutation retain all technical and biological structure of the cohort and only break the link with the disease label,
# so any residual inflation unrelated to group enters the null distribution and cancels out.
#
# Computation uses Frisch-Waugh-Lovell: M and the group vector are each residualised on the remaining
# covariates, after which the group coefficient of each probe reduces to an inner product of two vectors
# and each permutation is a single matrix multiplication. The coefficients are identical to those of limma.
#
# Environment: Windows + RStudio
# Location: <project root>/scripts/18_shared_signal.R
# ==============================================================

PROJ_ROOT <- "C:/blood_methylation_project"
DATA_ROOT <- "D:/blood_methylation_data"
SCRIPT_NAME <- "18_shared_signal"

SET_DIR <- file.path(DATA_ROOT, "analysis_sets")
RES_DIR <- file.path(DATA_ROOT, "ewas_final")
OUT_DIR <- file.path(PROJ_ROOT, "output", "18_shared")
if (!dir.exists(RES_DIR)) stop("Output of 17 not found: ", RES_DIR)
if (!dir.exists(OUT_DIR)) dir.create(OUT_DIR, recursive = TRUE)

source(file.path(PROJ_ROOT, "scripts", "00_logging.R"))
log_start(SCRIPT_NAME, proj_root = PROJ_ROOT)
source(file.path(PROJ_ROOT, "scripts", "00_plotting.R"))

set.seed(20260914)
N_PERM    <- 1000L
BETA_CLIP <- 0.001
TOP_P     <- 1e-4      # Selection threshold used for the "top probe" concordance

ROLE <- c(GSE145361 = "PD discovery", GSE111629 = "PD replication",
          GSE72774 = "PD sensitivity", GSE87648 = "IBD main",
          GSE112611 = "IBD paediatric", GSE152027 = "Negative control")

# For each pair: a is fixed, b is permuted (the smaller cohort, to save computation)
PAIRS <- list(
  list(id = "PC1", kind = "positive control", a = "GSE145361", b = "GSE111629"),
  list(id = "PC2", kind = "positive control", a = "GSE87648",  b = "GSE112611"),
  list(id = "M1",  kind = "primary criterion",   a = "GSE145361", b = "GSE87648"),
  list(id = "M2",  kind = "secondary",     a = "GSE111629", b = "GSE87648"),
  list(id = "NC1", kind = "negative control", a = "GSE145361", b = "GSE152027"),
  list(id = "NC2", kind = "negative control", a = "GSE87648",  b = "GSE152027")
)

# --------------------------------------------------------------
# Read the results and design matrices of 17
# --------------------------------------------------------------
ew <- list(); dz <- list()
for (g in names(ROLE)) {
  f1 <- file.path(RES_DIR, paste0(g, "_ewas_final.rds"))
  f2 <- file.path(RES_DIR, paste0(g, "_design.rds"))
  if (file.exists(f1)) ew[[g]] <- readRDS(f1)
  if (file.exists(f2)) dz[[g]] <- readRDS(f2)
}
say("EWAS results loaded: ", length(ew), " sets, design matrices ", length(dz), "")

# --------------------------------------------------------------
# Residualisation: return the samples x probes residual matrix and the QR used for residualisation
# --------------------------------------------------------------
make_resid <- function(g) {
  D <- dz[[g]]
  obj <- readRDS(file.path(SET_DIR, paste0(g, "_analysis_filtered.rds")))
  b <- obj$beta[D$probes, D$gsm, drop = FALSE]
  rm(obj); invisible(gc())
  b[!is.finite(b)] <- NA
  b[b < BETA_CLIP] <- BETA_CLIP; b[b > 1 - BETA_CLIP] <- 1 - BETA_CLIP
  M <- log2(b / (1 - b)); rm(b); invisible(gc())
  des <- D$design
  jg <- which(colnames(des) == "groupcase")
  X0 <- des[, -jg, drop = FALSE]
  q0 <- qr(X0)
  R <- qr.resid(q0, t(M))          # samples x probes
  rm(M); invisible(gc())
  list(R = R, q0 = q0, group = D$group, probes = D$probes)
}

coef_from <- function(st, gvec) {
  gres <- qr.resid(st$q0, gvec)
  den <- sum(gres^2)
  if (den <= 0) return(rep(NA_real_, ncol(st$R)))
  as.numeric(crossprod(gres, st$R)) / den
}

conc <- function(a, b) {
  ok <- is.finite(a) & is.finite(b)
  c(rho = suppressWarnings(stats::cor(a[ok], b[ok], method = "spearman")),
    r = suppressWarnings(stats::cor(a[ok], b[ok])),
    dir = mean(sign(a[ok]) == sign(b[ok])), n = sum(ok))
}

resid_cache <- list()
out <- list(); nulls <- list(); scat <- list()

for (P in PAIRS) {
  ga <- P$a; gb <- P$b
  if (is.null(ew[[ga]]) || is.null(ew[[gb]])) {
    say("Skipping ", P$id, ": results missing"); next
  }
  say("==== ", P$id, "  ", P$kind, ": ", ga, " (", ROLE[ga], ") vs ",
      gb, " (", ROLE[gb], ") ====")

  common <- intersect(ew[[ga]]$probe, ew[[gb]]$probe)
  say("  Common probes: ", length(common))
  ia <- match(common, ew[[ga]]$probe); ib <- match(common, ew[[gb]]$probe)
  ea <- ew[[ga]]$effect[ia]; eb <- ew[[gb]]$effect[ib]

  o <- conc(ea, eb)
  say("  Observed: Spearman rho = ", sprintf("%.4f", o[["rho"]]),
      ", Pearson r = ", sprintf("%.4f", o[["r"]]),
      ", sign concordance = ", sprintf("%.4f", o[["dir"]]))

  # Top-probe version: selected by P value in a, tested in b; the two are independent
  sel <- which(ew[[ga]]$p[ia] < TOP_P)
  if (length(sel) >= 50L) {
    ot <- conc(ea[sel], eb[sel])
    say("  Top probes (P < ", TOP_P, " in a, ", length(sel), " probes): rho = ",
        sprintf("%.4f", ot[["rho"]]), ", sign concordance = ", sprintf("%.4f", ot[["dir"]]))
  } else {
    ot <- c(rho = NA, r = NA, dir = NA, n = length(sel))
    say("  Fewer than 50 top probes (", length(sel), "); this version is not computed")
  }

  # Permutation
  if (is.null(resid_cache[[gb]])) {
    say("  Residualising ", gb, "...")
    t0 <- Sys.time()
    resid_cache[[gb]] <- make_resid(gb)
    say("  Time: ", sprintf("%.1f", as.numeric(difftime(Sys.time(), t0, units = "mins"))), " min")
  }
  st <- resid_cache[[gb]]
  jb <- match(common, st$probes)
  if (anyNA(jb)) stop(P$id, " common probes are missing from the residual matrix")
  gnum <- as.numeric(st$group == "case")
  base <- coef_from(st, gnum)
  chk <- stats::cor(base[jb], eb, use = "complete.obs")
  say("  Correlation between coefficients recomputed by residualisation and limma results = ", sprintf("%.6f", chk),
      if (chk < 0.999) "  [WARNING] the two should be almost identical; please check" else "")

  ra <- rank(ea)
  t0 <- Sys.time()
  pr <- numeric(N_PERM); pd <- numeric(N_PERM)
  for (i in seq_len(N_PERM)) {
    cf <- coef_from(st, sample(gnum))[jb]
    pr[i] <- stats::cor(ra, rank(cf))
    pd[i] <- mean(sign(ea) == sign(cf), na.rm = TRUE)
  }
  say("  ", N_PERM, " permutations, time ",
      sprintf("%.1f", as.numeric(difftime(Sys.time(), t0, units = "mins"))), " min")

  p_rho <- (1 + sum(pr >= o[["rho"]])) / (N_PERM + 1)
  p_dir <- (1 + sum(pd >= o[["dir"]])) / (N_PERM + 1)
  say("  Null rho: mean ", sprintf("%.4f", mean(pr)),
      ", SD ", sprintf("%.4f", stats::sd(pr)),
      ", maximum ", sprintf("%.4f", max(pr)))
  say("  Empirical P (one-sided): rho ", format.pval(p_rho, digits = 3),
      "; sign concordance ", format.pval(p_dir, digits = 3))
  z <- (o[["rho"]] - mean(pr)) / stats::sd(pr)
  say("  Z of the observed value relative to the null = ", sprintf("%.2f", z))

  out[[length(out) + 1]] <- data.frame(
    pair = P$id, kind = P$kind, a = ga, b = gb,
    n_probe = o[["n"]], rho = o[["rho"]], r = o[["r"]], dir = o[["dir"]],
    rho_top = ot[["rho"]], dir_top = ot[["dir"]], n_top = ot[["n"]],
    null_mean = mean(pr), null_sd = stats::sd(pr), z = z,
    p_rho = p_rho, p_dir = p_dir, stringsAsFactors = FALSE)
  nulls[[P$id]] <- data.frame(pair = P$id, kind = P$kind, rho = pr,
                              obs = o[["rho"]], stringsAsFactors = FALSE)
  sub <- sample(seq_along(common), min(60000L, length(common)))
  scat[[P$id]] <- data.frame(pair = P$id, kind = P$kind,
                             ea = ea[sub], eb = eb[sub], stringsAsFactors = FALSE)

  # If the primary criterion is significant, take the shared sites according to D7
  if (P$id == "M1" && p_rho < 0.05) {
    fa <- ew[[ga]]$fdr[ia]; fb <- ew[[gb]]$fdr[ib]
    sh <- which(fa < 0.05 & fb < 0.05 & sign(ea) == sign(eb))
    say("  Probes with FDR < 0.05 in both diseases and the same direction: ", length(sh))
    if (length(sh)) {
      write.csv(data.frame(probe = common[sh], effect_pd = ea[sh],
                           fdr_pd = fa[sh], effect_ibd = eb[sh], fdr_ibd = fb[sh]),
                file.path(OUT_DIR, "shared_probes.csv"), row.names = FALSE)
    }
  }
  say("")
}

rr <- do.call(rbind, out)
write.csv(rr, file.path(OUT_DIR, "shared_signal_results.csv"), row.names = FALSE)
