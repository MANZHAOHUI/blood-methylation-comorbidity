# ==============================================================
# Shared blood DNA methylation signatures of comorbid disorders (PD x IBD)
# Step 13: within-cohort case-control analysis (EWAS)
#
# Each data set is modelled separately; samples are not pooled. The output is the regression coefficient, standard error and
# P value of every probe - the later "sharing tests" compare these coefficients, not the beta values themselves,
# so the covariate specification of this step directly decides whether the conclusions of the whole paper hold.
#
# Model: M value ~ case-control + sex + age + eleven cell fractions + smoking score + batch
#   - age: chronological age where available; GSE145361 has no such field and uses DNAm age;
#     GSE152027 lacks 60% of chronological ages and also uses DNAm age (r = 0.897 there)
#   - cell fractions: the twelve types sum to 1, so one type must be dropped or the design matrix is singular
#   - batch: GSE87648 uses scan date (two batches of 191, perfectly balanced with diagnosis);
#     cohorts with array barcodes use the array ID; GSE72774 has neither
#   - smoking: GSE112611 is a paediatric cohort and the score cannot be computed for 52 samples; the term is not in its model
#
# This step also gives the genomic inflation factor lambda and QQ plots. A lambda clearly above 1
# indicates unadjusted structure, in which case the analysis must not simply proceed.
#
# Environment: Windows + RStudio
# Location: <project root>/scripts/13_ewas.R
# ==============================================================

PROJ_ROOT <- "C:/blood_methylation_project"
DATA_ROOT <- "D:/blood_methylation_data"
SCRIPT_NAME <- "13_ewas"

SET_DIR <- file.path(DATA_ROOT, "analysis_sets")
COV_DIR <- file.path(DATA_ROOT, "covariates")
MAP_DIR <- file.path(PROJ_ROOT, "output", "06_mapping")
RES_DIR <- file.path(DATA_ROOT, "ewas")
OUT_DIR <- file.path(PROJ_ROOT, "output", "13_ewas")
for (d in c(SET_DIR, COV_DIR)) if (!dir.exists(d)) stop("Directory does not exist: ", d)
for (d in c(RES_DIR, OUT_DIR)) {
  if (!dir.exists(d)) dir.create(d, recursive = TRUE)
  if (!dir.exists(d)) stop("Failed to create directory: ", d)
}

source(file.path(PROJ_ROOT, "scripts", "00_logging.R"))
log_start(SCRIPT_NAME, proj_root = PROJ_ROOT)
source(file.path(PROJ_ROOT, "scripts", "00_plotting.R"))
suppressPackageStartupMessages(library(limma))

BARCODE   <- "[0-9]{8,}_R[0-9]{2}C[0-9]{2}"
DROP_CT   <- "ct_Baso"        # The cell type dropped to avoid singularity caused by fractions summing to 1
BETA_CLIP <- 0.001            # Clip beta to (clip, 1-clip) before converting to M values
MAX_BATCH_LEVELS_RATIO <- 0.25  # Batch is not modelled if its number of levels exceeds this proportion of the sample size

ROLE <- c(GSE145361 = "PD discovery", GSE111629 = "PD replication",
          GSE72774 = "PD sensitivity", GSE87648 = "IBD main",
          GSE112611 = "IBD paediatric", GSE152027 = "Negative control")
ORDER <- names(ROLE)

# Age source and smoking term of each data set; reasons are given at the top of the script
AGE_SOURCE <- c(GSE145361 = "dnam", GSE152027 = "dnam",
                GSE111629 = "chrono", GSE72774 = "chrono",
                GSE87648 = "chrono", GSE112611 = "chrono")
USE_SMOKING <- c(GSE145361 = TRUE, GSE152027 = TRUE, GSE111629 = TRUE,
                 GSE72774 = TRUE, GSE87648 = TRUE, GSE112611 = FALSE)

slide_of <- function(g, gsm) {
  mf <- file.path(MAP_DIR, paste0(g, "_sample_map.csv"))
  if (!file.exists(mf)) return(rep(NA_character_, length(gsm)))
  m <- read.csv(mf, stringsAsFactors = FALSE, colClasses = "character")
  bc <- rep(NA_character_, nrow(m))
  hit <- regexpr(BARCODE, m$col_name) > 0
  bc[hit] <- regmatches(m$col_name, regexpr(BARCODE, m$col_name))
  sub("_R[0-9]{2}C[0-9]{2}$", "", bc)[match(gsm, m$gsm)]
}

files <- list.files(SET_DIR, pattern = "_analysis_filtered\\.rds$", full.names = TRUE)
if (!length(files)) stop("Filtered analysis objects generated by 09 not found")
say("To analyse: ", length(files), "")
say("")

summ <- list(); qqdat <- list(); vol <- list()

for (f in files) {
  obj <- readRDS(f)
  g <- obj$gse
  say("==== ", g, " (", ROLE[g], ") ====")

  cov <- read.csv(file.path(COV_DIR, paste0(g, "_covariates.csv")),
                  stringsAsFactors = FALSE)
  cov <- cov[match(colnames(obj$beta), cov$gsm), , drop = FALSE]
  if (anyNA(cov$gsm)) stop(g, ": covariates and matrix samples do not match")
  ph <- obj$pheno

  d <- data.frame(group = factor(as.character(ph$group),
                                 levels = c("control", "case")),
                  stringsAsFactors = FALSE)

  sx <- grep("^(sex|gender)$", names(ph), ignore.case = TRUE, value = TRUE)[1]
  d$sex <- if (is.na(sx)) NA else factor(toupper(substr(trimws(ph[[sx]]), 1, 1)))

  if (AGE_SOURCE[g] == "dnam") {
    d$age <- cov$dnam_age_horvath
    age_note <- "DNAm age"
  } else {
    ag <- grep("^age$|ageat", names(ph), ignore.case = TRUE, value = TRUE)[1]
    d$age <- suppressWarnings(as.numeric(ph[[ag]]))
    age_note <- "chronological age"
  }

  ct <- grep("^ct_", names(cov), value = TRUE)
  ct <- setdiff(ct, DROP_CT)
  for (k in ct) d[[k]] <- cov[[k]]

  if (isTRUE(USE_SMOKING[g])) d$smoking <- cov$dnam_smoking

  batch_note <- "none"
  if ("scan_date" %in% names(ph)) {
    d$batch <- factor(as.character(ph$scan_date)); batch_note <- "scan date"
  } else {
    sl <- slide_of(g, colnames(obj$beta))
    if (sum(!is.na(sl)) > 0.95 * length(sl)) {
      nl <- length(unique(sl))
      if (nl <= MAX_BATCH_LEVELS_RATIO * length(sl)) {
        d$batch <- factor(sl)
        batch_note <- paste0("array ID (", nl, " levels)")
      } else {
        batch_note <- paste0("array ID has too many levels (", nl, "), not modelled")
      }
    }
  }

  say("  Age source: ", age_note, "; smoking term: ",
      if (isTRUE(USE_SMOKING[g])) "included" else "not included",
      "; batch: ", batch_note)
  say("  Cell fractions in the model: ", length(ct), " types (dropped ", DROP_CT, ")")

  ok <- stats::complete.cases(d)
  if (sum(!ok) > 0) {
    say("  Removed because of missing covariates: ", sum(!ok), " samples")
    for (k in names(d)) {
      nmiss <- sum(!stats::complete.cases(d[[k]]))
      if (nmiss > 0) say("    ", k, " missing ", nmiss)
    }
  }
  d <- d[ok, , drop = FALSE]
  beta <- obj$beta[, ok, drop = FALSE]
  tb <- table(d$group)
  say("  Samples in the model: controls ", tb[["control"]], ", cases ", tb[["case"]])

  design <- stats::model.matrix(~ ., data = d)
  qrank <- qr(design)$rank
  say("  Design matrix ", nrow(design), " x ", ncol(design), ", rank ", qrank)
  if (qrank < ncol(design)) {
    say("  [WARNING] the design matrix is rank-deficient (collinearity); results unusable")
    next
  }
  say("  Residual degrees of freedom: ", nrow(design) - ncol(design))

  # Convert beta to M values
  b <- beta
  b[!is.finite(b)] <- NA
  b[b < BETA_CLIP] <- BETA_CLIP
  b[b > 1 - BETA_CLIP] <- 1 - BETA_CLIP
  M <- log2(b / (1 - b))
  rm(b); invisible(gc())

  fit <- limma::eBayes(limma::lmFit(M, design))
  coefname <- "groupcase"
  if (!coefname %in% colnames(fit$coefficients)) {
    say("  [ERROR] coefficient not found: ", coefname, ", actual columns: ",
        paste(colnames(fit$coefficients), collapse = ", ")); next
  }
  tt <- limma::topTable(fit, coef = coefname, number = Inf, sort.by = "none")
  res <- data.frame(probe = rownames(tt), beta_M = tt$logFC,
                    se_M = fit$stdev.unscaled[, coefname] * sqrt(fit$s2.post),
                    t = tt$t, p = tt$P.Value, fdr = tt$adj.P.Val,
                    stringsAsFactors = FALSE)

  chisq <- stats::qchisq(res$p, df = 1, lower.tail = FALSE)
  lambda <- stats::median(chisq, na.rm = TRUE) / stats::qchisq(0.5, 1)
  n_fdr <- sum(res$fdr < 0.05, na.rm = TRUE)
  say("  lambda = ", sprintf("%.3f", lambda),
      "; probes with FDR < 0.05: ", n_fdr,
      "; minimum P = ", format.pval(min(res$p, na.rm = TRUE), digits = 3))

  saveRDS(res, file.path(RES_DIR, paste0(g, "_ewas.rds")))
  write.csv(head(res[order(res$p), ], 200),
            file.path(OUT_DIR, paste0(g, "_top200.csv")), row.names = FALSE)

  summ[[g]] <- data.frame(gse = g, role = ROLE[g], disease = obj$disease,
                          n_control = tb[["control"]], n_case = tb[["case"]],
                          n_probe = nrow(res), lambda = lambda,
                          n_fdr05 = n_fdr, age_source = age_note,
                          smoking = isTRUE(USE_SMOKING[g]), batch = batch_note,
                          stringsAsFactors = FALSE)

  o <- order(res$p)
  ex <- -log10(stats::ppoints(nrow(res)))
  qqdat[[g]] <- data.frame(gse = g, lambda = lambda,
                           expected = ex, observed = -log10(res$p[o]),
                           stringsAsFactors = FALSE)
  vol[[g]] <- data.frame(gse = g, effect = res$beta_M,
                         logp = -log10(res$p), fdr = res$fdr,
                         stringsAsFactors = FALSE)
  say("")
  rm(obj, M, fit, beta); invisible(gc())
}

s_all <- do.call(rbind, summ)
write.csv(s_all, file.path(OUT_DIR, "ewas_summary.csv"), row.names = FALSE)
say("=== Summary ===")
print(s_all[, c("gse", "role", "n_control", "n_case", "lambda", "n_fdr05")])

