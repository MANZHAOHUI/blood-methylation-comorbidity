lab <- function(x) factor(paste0(x, "\n", ROLE[x]),
                          levels = paste0(ORDER, "\n", ROLE[ORDER]))

qd <- do.call(rbind, qqdat)
qd$panel <- lab(qd$gse)
ltxt <- unique(qd[, c("panel", "lambda")])
ltxt$lab <- paste0("lambda = ", sprintf("%.3f", ltxt$lambda))
p <- ggplot(qd, aes(expected, observed)) +
  geom_abline(slope = 1, intercept = 0, colour = "grey55",
              linetype = 2, linewidth = 0.4) +
  geom_point_big(size = 0.5, alpha = 0.55, colour = PAL[1]) +
  geom_text(data = ltxt, aes(x = -Inf, y = Inf, label = lab),
            hjust = -0.12, vjust = 1.6, size = 2.9, inherit.aes = FALSE) +
  facet_wrap(~ panel, ncol = 3, scales = "free") +
  labs(title = "Quantile-quantile plots of the within-cohort EWAS",
       subtitle = "Deviation above the diagonal beyond the extreme tail indicates residual uncorrected structure",
       x = expression(Expected~-log[10]*(P)),
       y = expression(Observed~-log[10]*(P))) +
  theme_paper()
save_fig(p, "fig13_ewas_qq", width = 10, height = 6)

vd <- do.call(rbind, vol)
vd$panel <- lab(vd$gse)
vd$sig <- ifelse(!is.na(vd$fdr) & vd$fdr < 0.05, "FDR < 0.05", "ns")
p <- ggplot(vd, aes(effect, logp, colour = sig)) +
  geom_point_big(size = 0.45, alpha = 0.5) +
  facet_wrap(~ panel, ncol = 3, scales = "free") +
  scale_colour_manual(values = c("FDR < 0.05" = PAL[2], ns = "grey72"),
                      name = NULL) +
  labs(title = "Case-control effects within each cohort",
       subtitle = "Effect size is the adjusted difference in M-value between cases and controls",
       x = "Effect size (M-value difference)",
       y = expression(-log[10]*(P))) +
  theme_paper() +
  guides(colour = guide_legend(override.aes = list(size = 2, alpha = 1)))
save_fig(p, "fig14_ewas_volcano", width = 10, height = 6)

