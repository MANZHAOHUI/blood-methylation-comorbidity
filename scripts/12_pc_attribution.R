# ==============================================================
# Shared blood DNA methylation signatures of comorbid disorders (PD x IBD)
# Step 12: attribution of principal components + check of the usability of DNAm age
#
# Two specific questions:
#
# 1. PC1 of GSE87648 explains 45.6%, far more than in the other five sets (11% to 15%).
#     What is this 45.6%? Batch has been excluded as a confounder (the two scan dates are perfectly balanced
#     between cases and controls); the remaining candidate is cell composition - newly diagnosed, untreated IBD
#     comes with active inflammation, and the granulocyte fraction is the largest axis of variation in whole-blood methylation anyway.
#     This step regresses each of the first ten principal components of every data set on every covariate in turn
#     and ranks, by the proportion explained, which covariate dominates which axis.
#     This is not an optional QC step: if the dominant axis on the IBD side is cell composition and on the PD
#     side it is not, comparing effect sizes without adjustment could easily produce a "shared signal" driven by
#     cell composition - the main false positive this study must guard against.
#
# 2. Whether DNAm age can stand in for age. GSE145361 has no age field at all and
#     GSE152027 lacks 60% of ages; both rely on it. In cohorts with chronological age,
#     the correlation and systematic offset between DNAm age and chronological age must be examined first.
#
# This step is descriptive only; no case-control inference is made.
#
# Environment: Windows + RStudio
# Location: <project root>/scripts/12_pc_attribution.R
# ==============================================================

