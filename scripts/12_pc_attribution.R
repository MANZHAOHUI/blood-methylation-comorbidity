# --------------------------------------------------------------
# Derive batch information from the array barcode (only for cohorts with barcodes)
# --------------------------------------------------------------
slide_of <- function(g, gsm) {
  mf <- file.path(MAP_DIR, paste0(g, "_sample_map.csv"))
  if (!file.exists(mf)) return(rep(NA_character_, length(gsm)))
  m <- read.csv(mf, stringsAsFactors = FALSE, colClasses = "character")
  bc <- rep(NA_character_, nrow(m))
  hit <- regexpr(BARCODE, m$col_name) > 0
  bc[hit] <- regmatches(m$col_name, regexpr(BARCODE, m$col_name))
  sl <- sub("_R[0-9]{2}C[0-9]{2}$", "", bc)
  sl[match(gsm, m$gsm)]
}

# Univariate proportion explained: R^2 for continuous variables, R^2 of lm for factors (equivalent to eta^2)
assoc <- function(y, x) {
  ok <- is.finite(y) & !is.na(x)
  if (sum(ok) < 20L) return(c(r2 = NA_real_, p = NA_real_))
  y <- y[ok]; x <- x[ok]
  if (is.character(x)) x <- factor(x)
  if (is.factor(x)) {
    x <- droplevels(x)
    if (nlevels(x) < 2L || nlevels(x) > 60L) return(c(r2 = NA_real_, p = NA_real_))
  } else {
    x <- as.numeric(x)
    if (stats::sd(x) == 0) return(c(r2 = NA_real_, p = NA_real_))
  }
  fit <- stats::lm(y ~ x)
  sm <- summary(fit)
  f <- sm$fstatistic
  p <- if (is.null(f)) NA_real_ else
    stats::pf(f[1], f[2], f[3], lower.tail = FALSE)
  c(r2 = unname(sm$r.squared), p = unname(p))
}

res <- list(); agecmp <- list(); pcvar <- list()

for (f in files) {
  obj <- readRDS(f)
  g <- obj$gse
  say("==== ", g, " ====")

  cf <- file.path(COV_DIR, paste0(g, "_covariates.csv"))
  if (!file.exists(cf)) { say("  Covariate file missing, skipped"); next }
  cov <- read.csv(cf, stringsAsFactors = FALSE)
  cov <- cov[match(colnames(obj$beta), cov$gsm), , drop = FALSE]
  if (anyNA(cov$gsm)) stop(g, ": covariates and matrix samples do not match")

  ph <- obj$pheno
  vars <- list()
  vars[["case/control"]] <- as.character(ph$group)
  sx <- grep("^(sex|gender)$", names(ph), ignore.case = TRUE, value = TRUE)[1]
  if (!is.na(sx)) vars[["sex"]] <- toupper(substr(trimws(ph[[sx]]), 1, 1))
  ag <- grep("^age$|ageat", names(ph), ignore.case = TRUE, value = TRUE)[1]
  if (!is.na(ag)) vars[["chronological age"]] <- suppressWarnings(as.numeric(ph[[ag]]))
  if ("scan_date" %in% names(ph)) vars[["batch (scan date)"]] <- as.character(ph$scan_date)
  sl <- slide_of(g, colnames(obj$beta))
  if (sum(!is.na(sl)) > 0.8 * length(sl)) vars[["batch (slide)"]] <- sl
  vars[["DNAm age"]] <- cov$dnam_age_horvath
  vars[["DNAm smoking"]] <- cov$dnam_smoking
  for (k in grep("^ct_", names(cov), value = TRUE)) vars[[sub("^ct_", "", k)]] <- cov[[k]]

  say("  Covariates: ", length(vars), "", paste(names(vars), collapse = ", "))

  # Principal components
  v <- apply(obj$beta, 1, stats::var, na.rm = TRUE)
  top <- names(sort(v, decreasing = TRUE))[seq_len(min(N_PROBE, length(v)))]
  m <- obj$beta[top, , drop = FALSE]
  m[!is.finite(m)] <- NA
  m <- m[stats::complete.cases(m), , drop = FALSE]
  pr <- stats::prcomp(t(m), center = TRUE, scale. = FALSE)
  ve <- 100 * pr$sdev^2 / sum(pr$sdev^2)
  npc <- min(N_PC, ncol(pr$x))
  say("  The first ", npc, " principal components explain cumulatively ", sprintf("%.1f%%", sum(ve[1:npc])))
  pcvar[[g]] <- data.frame(gse = g, pc = seq_len(npc), ve = ve[1:npc])

  rows <- list()
  for (i in seq_len(npc)) for (nm in names(vars)) {
    a <- assoc(pr$x[, i], vars[[nm]])
    rows[[length(rows) + 1]] <- data.frame(
      gse = g, pc = i, pc_var = ve[i], covariate = nm,
      r2 = a[["r2"]], p = a[["p"]], stringsAsFactors = FALSE)
  }
  rr <- do.call(rbind, rows)
  res[[g]] <- rr

  best <- rr[rr$pc == 1 & !is.na(rr$r2), ]
  best <- best[order(-best$r2), ][1:min(4, nrow(best)), ]
  say("  PC1 ( ", sprintf("%.1f%%", ve[1]), "): covariates with the highest explanatory power: ")
  for (i in seq_len(nrow(best))) {
    say("    ", best$covariate[i], "  R2 = ", sprintf("%.3f", best$r2[i]),
        "  p = ", format.pval(best$p[i], digits = 2))
  }

  # DNAm age against chronological age
  if (!is.null(vars[["chronological age"]])) {
    a <- vars[["chronological age"]]; b <- cov$dnam_age_horvath
    ok <- is.finite(a) & is.finite(b)
    if (sum(ok) >= 20L) {
      say("  DNAm age vs chronological age: r = ", sprintf("%.3f", cor(a[ok], b[ok])),
          ", median offset ", sprintf("%+.1f", median(b[ok] - a[ok])), " years, n = ", sum(ok))
      agecmp[[g]] <- data.frame(gse = g, chrono = a[ok], dnam = b[ok],
                                group = as.character(ph$group)[ok],
                                stringsAsFactors = FALSE)
    }
  }
  say("")
  rm(obj, m, pr); invisible(gc())
}

res_all <- do.call(rbind, res)
