EPIC_SETS <- "GSE112611"

# Recompute only the cohorts given here; NULL means all. The slowest of the three covariates, BMIQ normalisation,
# takes tens of minutes to three hours per set and more than ten hours for all, so selective runs are supported by default.
ONLY <- NULL          # e.g. c("GSE112611")

# The raw matrix without any probe selection (rds/<GSE>_beta.rds) is used,
# not the analysis object generated by 07 - the latter is already restricted to the common probe set,
# which is a particular disadvantage for the EPIC cohort: only a third of the 600 probes of the twelve-cell-type reference remain there.
RAW_DIR <- RDS_DIR <- file.path(DATA_ROOT, "rds")
MAP_DIR <- file.path(PROJ_ROOT, "output", "06_mapping")

load_raw_beta <- function(g, keep_gsm) {
  bf <- file.path(RAW_DIR, paste0(g, "_beta.rds"))
  mf <- file.path(MAP_DIR, paste0(g, "_sample_map.csv"))
  if (!file.exists(bf) || !file.exists(mf)) return(NULL)
  m <- read.csv(mf, stringsAsFactors = FALSE, colClasses = "character")
  b <- readRDS(bf)
  idx <- as.integer(m$col_pos_in_data) - 1L     # The probe ID column was removed when 04 saved the file
  if (max(idx) > ncol(b)) stop(g, ": column position out of range")
  b <- b[, idx, drop = FALSE]
  colnames(b) <- m$gsm
  miss <- setdiff(keep_gsm, colnames(b))
  if (length(miss)) stop(g, ": samples missing from the raw matrix: ", length(miss), "")
  b[, keep_gsm, drop = FALSE]
}

files <- list.files(SET_DIR, pattern = "_analysis\\.rds$", full.names = TRUE)
files <- files[!grepl("_filtered", files)]
if (!is.null(ONLY)) files <- files[basename(files) %in% paste0(ONLY, "_analysis.rds")]
say("To process: ", length(files), "")
say("")

all_cov <- list()

for (f in files) {
  obj <- readRDS(f)
  g <- obj$gse
  raw <- load_raw_beta(g, colnames(obj$beta))
  if (is.null(raw)) {
    say("==== ", g, " ====")
    say("  Raw matrix or mapping table not found; falling back to the analysis object (fewer probes, estimates will be worse)")
    beta <- obj$beta
  } else {
    beta <- raw; rm(raw)
  }
  say("==== ", g, "  ", nrow(beta), " probes x ", ncol(beta), " samples ====")

  cov <- data.frame(gse = g, gsm = colnames(beta),
                    group = as.character(obj$pheno$group),
                    stringsAsFactors = FALSE)

  # ---- 1. leukocyte fractions ----
  ref <- if (g %in% EPIC_SETS) REFEPIC else REF450
  ov <- intersect(rownames(ref), rownames(beta))
  say("  Reference probes found: ", length(ov), " / ", nrow(ref),
      " (", sprintf("%.1f%%", 100 * length(ov) / nrow(ref)), ")")
  r <- tryCatch({
    est <- EpiDISH::epidish(beta.m = beta, ref.m = ref, method = "RPC")$estF
    est <- est[cov$gsm, , drop = FALSE]
    colnames(est) <- paste0("ct_", colnames(est))
    cov <- cbind(cov, as.data.frame(est))
    say("  Cell fractions: ", ncol(est), " types, median row sum ",
        sprintf("%.3f", median(rowSums(est))))
    "pass"
  }, error = function(e) paste0("failed: ", conditionMessage(e)))
  say("  Cell fractions -> ", r)

  # ---- 2. DNAm age ----
  r <- tryCatch({
    ma <- dnaMethyAge::methyAge(beta, clock = "HorvathS2013", do_plot = FALSE)
    say("  Columns returned by methyAge: ", paste(names(ma), collapse = ", "))
    agecol <- setdiff(names(ma), c("Sample", "sample", "ID"))[1]
    idcol <- intersect(c("Sample", "sample", "ID"), names(ma))[1]
    v <- ma[[agecol]][match(cov$gsm, ma[[idcol]])]
    cov$dnam_age_horvath <- as.numeric(v)
    say("  DNAm age: median ", sprintf("%.1f", median(cov$dnam_age_horvath, na.rm = TRUE)),
        ", missing ", sum(is.na(cov$dnam_age_horvath)))
    "pass"
  }, error = function(e) paste0("failed: ", conditionMessage(e)))
  say("  DNAm age -> ", r)

  # ---- 3. DNAm smoking score ----
  r <- tryCatch({
    ss <- EpiSmokEr::SSc(dataset = beta)
    say("  SSc returned: ", paste(class(ss), collapse = "/"),
        ", columns ", paste(names(as.data.frame(ss)), collapse = ", "))
    ss <- as.data.frame(ss)
    sc <- ss[[ncol(ss)]]
    nmv <- rownames(ss)
    cov$dnam_smoking <- as.numeric(sc)[match(cov$gsm, nmv)]
    say("  Smoking score: median ", sprintf("%.3f", median(cov$dnam_smoking, na.rm = TRUE)),
        ", missing ", sum(is.na(cov$dnam_smoking)))
    "pass"
  }, error = function(e) paste0("failed: ", conditionMessage(e)))
  say("  Smoking score -> ", r)

  # ---- check: only GSE72774 has existing results for comparison ----
  if (g == "GSE72774") {
    ph <- obj$pheno
    if ("dnam_age_horvath" %in% names(cov) && "dnamage" %in% names(ph)) {
      a <- cov$dnam_age_horvath; b <- suppressWarnings(as.numeric(ph$dnamage))
      ok <- is.finite(a) & is.finite(b)
      say("  [check] our Horvath age vs dnamage shipped with the data: ",
          "r = ", sprintf("%.4f", cor(a[ok], b[ok])),
          ", mean difference ", sprintf("%.2f", mean(a[ok] - b[ok])), " years, n = ", sum(ok))
    }
    pair <- list(ct_Mono = "mono", ct_NK = "nk")
    for (k in names(pair)) {
      if (k %in% names(cov) && pair[[k]] %in% names(ph)) {
        a <- cov[[k]]; b <- suppressWarnings(as.numeric(ph[[pair[[k]]]]))
        ok <- is.finite(a) & is.finite(b)
        say("  [check] ", k, " vs shipped ", pair[[k]], ": r = ",
            sprintf("%.3f", cor(a[ok], b[ok])))
      }
    }
    gr <- intersect(c("ct_Neu", "ct_Eos", "ct_Baso"), names(cov))
    if (length(gr) && "gran" %in% names(ph)) {
      a <- rowSums(cov[, gr, drop = FALSE])
      b <- suppressWarnings(as.numeric(ph$gran))
      ok <- is.finite(a) & is.finite(b)
      say("  [check] neutrophils + eosinophils + basophils vs shipped gran: r = ",
          sprintf("%.3f", cor(a[ok], b[ok])))
    }
  }

  write.csv(cov, file.path(COV_DIR, paste0(g, "_covariates.csv")), row.names = FALSE)
  all_cov[[g]] <- cov
  say("  Saved ", g, "_covariates.csv")
  say("")
  rm(obj, beta); invisible(gc())
}

