# ==============================================================
# Shared blood DNA methylation signatures of comorbid disorders (PD x IBD)
# Step 11: compute three groups of covariates
#
#   (1) leukocyte fractions   EpiDISH RPC, twelve-cell-type reference matrix specific to 450K
#   (2) DNAm age              dnaMethyAge, HorvathS2013
#   (3) DNAm smoking score    EpiSmokEr
#
# An important choice: all three are computed on the matrices before filtering, not on those filtered in 09.
# The filtering in 09 serves the association tests (removing sex-chromosome, SNP and non-specific probes),
# whereas each of these three depends on a fixed set of reference probes; the more reference probes are filtered out,
# the worse the estimate. The filtered sets are used for modelling only, not for estimating covariates.
#
# The script has two built-in correctness checks, both using results shipped with GSE72774:
#   - our HorvathS2013 age vs its own dnamage
#   - our granulocyte/monocyte and other fractions vs its own Houseman estimates
# A mismatch would indicate a problem with our calls, and it would be found before other cohorts are used.
#
# The calling interfaces of the three packages had not been tested beforehand, so the script first prints the function signatures
# and then tries each one inside tryCatch; the failure of one item does not prevent the others from being saved.
#
# Environment: Windows + RStudio
# Location: <project root>/scripts/11_covariates.R
# ==============================================================

