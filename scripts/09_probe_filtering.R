# ==============================================================
# Shared blood DNA methylation signatures of comorbid disorders (PD x IBD)
# Step 09: probe filtering (implements decision D2)
#
# Four classes of probes are removed in turn; every step reports the number removed and the number remaining:
#   (1) sex-chromosome probes (chrX / chrY)
#   (2) probes with a common SNP at the CpG site itself or at the single-base extension site
#   (3) cross-reactive / multi-mapping probes (Chen 2013 and the 450K bowtie multimap list)
#   (4) probes with a high missing rate in any data set
#
# For the EPIC replication set two EPIC-specific lists of non-specific probes are added.
#
# Output: the two filtered probe sets and the analysis objects restricted to the new sets,
# so that 07 need not be re-run.
#
# Environment: Windows + RStudio
# Location: <project root>/scripts/09_probe_filtering.R
# ==============================================================

PROJ_ROOT <- "C:/blood_methylation_project"
DATA_ROOT <- "D:/blood_methylation_data"

RDS_DIR <- file.path(DATA_ROOT, "rds")
SET_DIR <- file.path(DATA_ROOT, "analysis_sets")
REF_DIR <- file.path(DATA_ROOT, "probe_lists")
OUT_DIR <- file.path(PROJ_ROOT, "output", "09_probes")
for (d in c(RDS_DIR, SET_DIR, REF_DIR)) if (!dir.exists(d)) stop("Directory does not exist: ", d)
if (!dir.exists(OUT_DIR)) dir.create(OUT_DIR, recursive = TRUE)
if (!dir.exists(OUT_DIR)) stop("Failed to create directory: ", OUT_DIR)

source(file.path(PROJ_ROOT, "scripts", "00_logging.R"))
log_start("09_probe_filtering", proj_root = PROJ_ROOT)

# Preset thresholds (fixed before seeing results)
MAF_CUT     <- 0.01   # Minor allele frequency of SNPs at the CpG site or the single-base extension site
MISS_CUT    <- 0.05   # Upper limit of the missing rate of a single probe in a data set

say("Thresholds: remove if SNP minor allele frequency > ", MAF_CUT, "; remove if probe missing rate > ",
    MISS_CUT, "")
say("")

# --------------------------------------------------------------
# Read list files: uniformly take probe IDs starting with cg/ch from the first column
# --------------------------------------------------------------
read_probe_list <- function(fname) {
  p <- file.path(REF_DIR, fname)
  if (!file.exists(p)) { say("  [missing] ", fname); return(character(0)) }
  x <- readLines(p, warn = FALSE)
  x <- x[nzchar(trimws(x))]
  first <- sub("[,\t].*$", "", x)
  first <- gsub('^"|"$', "", trimws(first))
  ids <- unique(first[grepl("^(cg|ch\\.)", first)])
  say("  ", fname, " -> ", length(ids), " probe IDs")
  ids
}

say("=== Reading the lists of non-specific probes ===")
xr_450k <- unique(c(
  read_probe_list("48639-non-specific-probes-Illumina450k.csv"),
  read_probe_list("HumanMethylation450_15017482_v.1.1_hg19_bowtie_multimap.txt")))
say("  450K after merging: ", length(xr_450k), "")

xr_epic <- unique(c(
  read_probe_list("13059_2016_1066_MOESM1_ESM.csv"),
  read_probe_list("1-s2.0-S221359601630071X-mmc2.txt"),
  read_probe_list("1-s2.0-S221359601630071X-mmc3.txt")))
say("  EPIC after merging: ", length(xr_epic), "")
say("")

# --------------------------------------------------------------
say("=== Reading the annotation and flagging probes to remove ===")
anno <- readRDS(file.path(REF_DIR, "anno450k.rds"))
say("  Annotation: ", nrow(anno), " rows")

sex_probes <- rownames(anno)[anno$chr %in% c("chrX", "chrY")]
say("  Sex-chromosome probes: ", length(sex_probes))

cpg_maf <- suppressWarnings(as.numeric(anno$CpG_maf))
sbe_maf <- suppressWarnings(as.numeric(anno$SBE_maf))
snp_probes <- rownames(anno)[
  (!is.na(cpg_maf) & cpg_maf > MAF_CUT) | (!is.na(sbe_maf) & sbe_maf > MAF_CUT)]
say("  Probes with a common SNP at the CpG or single-base extension site: ", length(snp_probes))
say("    of which at the CpG site: ", sum(!is.na(cpg_maf) & cpg_maf > MAF_CUT),
    ", at the extension site: ", sum(!is.na(sbe_maf) & sbe_maf > MAF_CUT))
say("")

# --------------------------------------------------------------
# Probes with a high missing rate in each data set
# --------------------------------------------------------------
say("=== High-missingness probes in each data set ===")
set_files <- list.files(SET_DIR, pattern = "_analysis\\.rds$", full.names = TRUE)
if (!length(set_files)) stop("Analysis objects generated by 07 not found; directory: ", SET_DIR)

high_miss_main <- character(0)
high_miss_repl <- character(0)
for (f in set_files) {
  obj <- readRDS(f)
  fr <- rowMeans(!is.finite(obj$beta))
  bad <- names(fr)[fr > MISS_CUT]
  say("  ", obj$gse, " (", obj$probe_set, " set) probes with missing rate > ", MISS_CUT,
      ": ", length(bad))
  if (obj$probe_set == "main") high_miss_main <- union(high_miss_main, bad)
  else high_miss_repl <- union(high_miss_repl, bad)
  rm(obj); invisible(gc())
}
say("  High-missingness probes merged within the primary analysis set: ", length(high_miss_main))
say("  High-missingness probes merged within the replication set: ", length(high_miss_repl))
say("")

# --------------------------------------------------------------
# Filter layer by layer
# --------------------------------------------------------------
filter_set <- function(probes, label, xr, high_miss) {
  say("=== ", label, " ===")
  say("  Start: ", length(probes))
  steps <- list(
    list("sex chromosomes", sex_probes),
    list("common SNPs", snp_probes),
    list("non-specific / multi-mapping", xr),
    list("high missingness", high_miss))
  kept <- probes
  tab <- data.frame(step = character(0), removed = integer(0),
                    remaining = integer(0), stringsAsFactors = FALSE)
  for (s in steps) {
    n0 <- length(kept)
    kept <- setdiff(kept, s[[2]])
    say("  removed ", s[[1]], " ", n0 - length(kept), ", remaining ", length(kept))
    tab <- rbind(tab, data.frame(step = s[[1]], removed = n0 - length(kept),
                                 remaining = length(kept),
                                 stringsAsFactors = FALSE))
  }
  say("  Final: ", length(kept), ", removed in total ",
      length(probes) - length(kept), " ( ",
      sprintf("%.1f%%", 100 * (1 - length(kept) / length(probes))), ")")
  say("")
  list(probes = kept, table = tab)
}

probes_main <- readRDS(file.path(RDS_DIR, "probes_main_450k.rds"))
probes_repl <- readRDS(file.path(RDS_DIR, "probes_replication_epic.rds"))

res_main <- filter_set(probes_main, "primary analysis set (5 sets, 450K)", xr_450k, high_miss_main)
res_repl <- filter_set(probes_repl, "replication set (including the paediatric EPIC cohort)",
                       unique(c(xr_450k, xr_epic)), high_miss_repl)

saveRDS(res_main$probes, file.path(RDS_DIR, "probes_main_filtered.rds"))
saveRDS(res_repl$probes, file.path(RDS_DIR, "probes_repl_filtered.rds"))
write.csv(res_main$table, file.path(OUT_DIR, "filter_steps_main.csv"), row.names = FALSE)
write.csv(res_repl$table, file.path(OUT_DIR, "filter_steps_repl.csv"), row.names = FALSE)

# --------------------------------------------------------------
# Restrict the analysis objects to the new sets to avoid re-running 07
# --------------------------------------------------------------
say("=== Restricting the analysis objects ===")
for (f in set_files) {
  obj <- readRDS(f)
  keep <- if (obj$probe_set == "main") res_main$probes else res_repl$probes
  hit <- intersect(rownames(obj$beta), keep)
  if (length(hit) != length(keep)) {
    stop(obj$gse, " lacks probes of the filtered set: ", length(keep) - length(hit), "")
  }
  obj$beta <- obj$beta[keep, , drop = FALSE]
  obj$probe_set_filtered <- TRUE
  out <- sub("_analysis\\.rds$", "_analysis_filtered.rds", f)
  saveRDS(obj, out, compress = FALSE)
  say("  ", obj$gse, ": ", nrow(obj$beta), " probes x ", ncol(obj$beta), " samples -> ",
      basename(out))
  rm(obj); invisible(gc())
}

log_stop()
